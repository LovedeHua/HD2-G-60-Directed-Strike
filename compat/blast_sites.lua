--          radius 3.0 / depth 2.0 / above 2.0，那是给"ping 空地"设计的宽松值）。
--
--   ★★ 为什么必须单独收紧（2026-10-03 实机数据）★★
--   G-60 的爆炸 = `ExplosionType 351 → damageId 345`：
--     `damage 1800 / structDamage 1800 / destroy(拆毁力) 40`，**内半径 4 m** / 外半径 12 m。
