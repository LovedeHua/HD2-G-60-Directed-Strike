package.path='src/?.lua;'..package.path
local P=require('g60.arrival_policy')
local n=0
local function test(name,fn) fn();n=n+1;print('PASS '..name) end
test('current arrival tolerance: 0.8 m succeeds, vanilla 2.5 m does not',function()
    assert(P.step(1,{0,0,0},{0.8,0,0},true,'a')=='detonate')
    assert(P.step(1,{0,0,0},{0.801,0,0},true,'a')=='guide')
    assert(P.step(1,{0,0,0},{2.5,0,0},true,'a')=='guide')
end)
test('transit waypoint cannot detonate, even at zero distance',function()
    assert(P.step(1,{0,0,0},{0,0,0},false,'a')=='guide')
end)
test('no progress returns to search, new stage and real progress reset watchdog',function()
    local _,p=P.step(0,{0,0,0},{10,0,0},true,'a')
    assert(P.step(4,{0,0,0},{10,0,0},true,'a',p)=='search')
    assert(P.step(4,{1,0,0},{10,0,0},true,'a',p)=='guide')
    assert(P.step(4,{0,0,0},{10,0,0},true,'b',p)=='guide')
end)
test('moving point and overshoot are evaluated now, not along an old segment',function()
    local _,p=P.step(0,{-2,0,0},{0,0,0},true,'a')
    assert(P.step(0.1,{2,0,0},{0,0,0},true,'a',p)=='guide')
    assert(P.step(0.1,{0,0,0},{2,0,0},true,'a',p)=='guide')
end)
test('exact elapsed ticks including low-half rollover and invalid clock',function()
    assert(P.elapsed('0000000100000001','00000000ffffffff')==2)
    assert(P.elapsed('0000000001d905c0','00000000000f4240')==30000000)
    assert(not pcall(P.elapsed,'0000000000000000','0000000000000001'))
end)
test('Titan cylinder allows lateral arrival without raising the successful blast-height band',function()
    local region={radius=1.75,depth=0.8}
    assert(P.step(1,{1.5,0,-0.5},{0,0,0},true,'titan',nil,region)=='detonate')
    assert(P.step(1,{1.75,0,-0.8},{0,0,0},true,'titan',nil,region)=='detonate')
    for _,own in ipairs({{1.751,0,-0.4},{1.3,1.3,-0.4},{0,0,0.001},{0,0,-0.801}}) do
        assert(P.step(1,own,{0,0,0},true,'titan',nil,region)=='guide')
    end
end)
test('arrival region never arms transit waypoints or expands other enemy tolerance',function()
    local own,goal={1.5,0,-0.5},{0,0,0};local region={radius=1.75,depth=0.8}
    assert(P.step(1,own,goal,false,'transit',nil,region)=='guide')
    assert(P.step(1,own,goal,true,'vanilla')=='guide')
    assert(P.step(1,own,{4,0,0},true,'moving',nil,region)=='guide')
    assert(not pcall(P.step,1,own,goal,true,'bad',nil,{radius=0/0,depth=0.8}))
end)
print('RESULT '..n..' passed; 0 failed')
